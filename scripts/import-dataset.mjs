import { readFile } from 'node:fs/promises';
import { createClient } from '@supabase/supabase-js';
const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SECRET_KEY;
if (!url || !key) throw new Error('Configura SUPABASE_URL y SUPABASE_SECRET_KEY en .env local.');
const db = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
const expectedRows = 1011;
const rows = JSON.parse(await readFile('data/smoke_detection_1011.json', 'utf8'));
if (rows.length !== expectedRows || new Set(rows.map(r => r.source_row)).size !== expectedRows) throw new Error(`Se requieren exactamente ${expectedRows} registros únicos.`);
const { error } = await db.from('smoke_readings').upsert(rows, { onConflict: 'dataset_id,source_row', ignoreDuplicates: true });
if (error) throw new Error(`Importacion fallida (${error.code}). Aplica primero la migracion SQL.`);
const { count, error: checkError } = await db.from('smoke_readings').select('*', { count: 'exact', head: true }).eq('dataset_id', rows[0].dataset_id);
if (checkError || count !== expectedRows) throw new Error(`La verificación remota no confirma ${expectedRows} registros.`);
const { error: refreshError } = await db.rpc('refresh_demo_dataset');
if (refreshError) throw new Error(`No se pudieron actualizar los nodos demostrativos (${refreshError.code}). Aplica la migración de 1,011 registros.`);
const { count: mapped, error: mappedError } = await db.from('demo_node_readings').select('*', { count: 'exact', head: true }).eq('dataset_id', rows[0].dataset_id);
if (mappedError || mapped !== expectedRows) throw new Error(`La asignación de nodos no confirma ${expectedRows} registros.`);
console.log(`Supabase: ${expectedRows} registros y sus nodos demostrativos verificados. Repetir el comando no crea duplicados.`);
