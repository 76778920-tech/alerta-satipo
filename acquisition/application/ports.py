from typing import Protocol


class SourcePort(Protocol):
    def fetch(self) -> list[dict]: ...


class RepositoryPort(Protocol):
    def save_batch(self, records: list[dict]) -> dict: ...
    def history(self, limit: int = 100, node_id: str | None = None) -> list[dict]: ...
    def pending(self) -> list[dict]: ...
    def acknowledge(self, event_id: str) -> None: ...
    def failed(self, event_id: str) -> None: ...


class ModelPort(Protocol):
    def predict(self, features: list[float]) -> dict: ...


class CommunicationPort(Protocol):
    """El receptor debe deduplicar por event_id y confirmar ese mismo ID."""
    def send(self, event: dict) -> str: ...
